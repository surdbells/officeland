<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Models\Redirect;
use Illuminate\Console\Command;

/**
 * Generates the Caddy redirect snippet from the `redirects` table (§14b).
 *
 * ── Why Caddy and not PHP ────────────────────────────────────────────────
 * D-009 puts no application in the request path, and a redirect is the last
 * place to make an exception. Legacy URLs are hit by crawlers in bulk during
 * the weeks after cutover — exactly when the site is under the most scrutiny —
 * and routing all of that through PHP would put the framework on the hot path
 * for traffic that produces no revenue and no page.
 *
 * A generated snippet keeps the database as the editable source of truth while
 * the serving cost stays a hash lookup in the edge.
 *
 * ── Why a `map` and not thousands of `redir` lines ───────────────────────
 * D-007 expects 5,063 legacy product URLs on top of the 161 categories. As
 * individual matchers that is 10,000+ Caddyfile lines, each one a named
 * matcher Caddy has to evaluate. `map` is a single lookup regardless of size.
 *
 * ── 410 is not 404, and the difference is deliberate ─────────────────────
 * A 410 tells a crawler the URL is deliberately gone and will not return, and
 * it is dropped from the index faster and more permanently than a 404. It is
 * the honest answer for legacy junk — merchandising pseudo-categories, expired
 * campaign URLs — that has no successor and should not inherit one.
 */
final class PublishRedirects extends Command
{
    protected $signature = 'redirects:publish
                            {--output=/etc/caddy/redirects.caddy : Where to write the snippet.}
                            {--print : Write to stdout instead, for inspection.}';

    protected $description = 'Generate the Caddy redirect snippet from the redirects table';

    public function handle(): int
    {
        /** @var list<Redirect> $redirects */
        $redirects = Redirect::query()->orderBy('from_path')->get()->all();

        if ($redirects === []) {
            $this->warn('No redirects to publish. Run `redirects:import --apply` first.');
        }

        $snippet = $this->render($redirects);

        if ($this->option('print')) {
            $this->line($snippet);

            return self::SUCCESS;
        }

        $output = (string) $this->option('output');

        if (@file_put_contents($output, $snippet) === false) {
            $this->error("Could not write {$output}.");

            return self::FAILURE;
        }

        $this->info(sprintf('Wrote %d redirect(s) to %s.', count($redirects), $output));
        $this->comment('Caddy re-reads this on reload: docker compose restart api');

        return self::SUCCESS;
    }

    /** @param list<Redirect> $redirects */
    private function render(array $redirects): string
    {
        $moved = [];
        $gone = [];

        foreach ($redirects as $redirect) {
            if ($redirect->isGone()) {
                $gone[] = $this->quote($redirect->from_path);

                continue;
            }

            $moved[] = sprintf(
                "\t%s %s %d",
                $this->quote($redirect->from_path),
                $this->quote((string) $redirect->to_path),
                $redirect->status_code,
            );
        }

        $lines = [
            '# GENERATED by `php artisan redirects:publish` — do not hand-edit.',
            '#',
            '# Source of truth is the `redirects` table; the reviewed map lives in',
            '# docs/REDIRECT_MAP.csv (D-007, D-016). Regenerate after any change.',
            '',
        ];

        if ($moved !== []) {
            /*
             * `default ""` matters: without it an unmatched path leaves the
             * placeholder as the literal string "-" or empty depending on
             * Caddy's version, and the matcher below would fire for every
             * request on the site.
             */
            $lines[] = 'map {path} {ol_to} {ol_status} {';
            $lines = array_merge($lines, $moved);
            $lines[] = "\tdefault \"\" \"\"";
            $lines[] = '}';
            $lines[] = '';
            $lines[] = '@ol_moved not vars {ol_to} ""';
            $lines[] = 'redir @ol_moved {ol_to} {ol_status}';
            $lines[] = '';
        }

        if ($gone !== []) {
            $lines[] = '# Deliberately gone (410), not missing (404). A 410 is dropped from';
            $lines[] = '# the index faster and does not keep being re-crawled.';
            $lines[] = '#';
            $lines[] = '# Wrapped in `handle`, not a bare `respond`. Caddy evaluates directives';
            $lines[] = '# in a fixed order in which `respond` comes AFTER `handle`, so a bare';
            $lines[] = '# respond loses to the static handler and the URL 404s instead —';
            $lines[] = '# which is exactly what it did. Inside a handle it joins the same';
            $lines[] = '# mutually-exclusive group and wins by appearing first.';
            $lines[] = '@ol_gone path '.implode(' ', $gone);
            $lines[] = 'handle @ol_gone {';
            $lines[] = "\trespond 410";
            $lines[] = '}';
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * Caddy treats whitespace as a separator and `{}` as placeholders, so every
     * path is quoted. A legacy URL with a space in it is exactly the kind of
     * row that would otherwise turn into a syntax error at reload time — on a
     * production edge, during a cutover.
     */
    private function quote(string $value): string
    {
        return '"'.str_replace(['\\', '"'], ['\\\\', '\\"'], $value).'"';
    }
}
