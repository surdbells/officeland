const NAMES_BEGIN = '  // === generated by tools/icons.mjs - do not edit ===';
const NAMES_END = '  // === end generated ===';
const CASES_BEGIN = '        <!-- generated by tools/icons.mjs - do not edit -->';
const CASES_END = '        <!-- end generated -->';

/**
 * The children of a lucide <svg>, reindented for the template.
 *
 * Every stroke attribute lives on the wrapping <svg> in icon.ts, so only the
 * shapes are taken. A shape carrying a hard-coded colour would ignore that and
 * paint itself regardless of the text it sits in - so the extraction rejects
 * one rather than shipping an icon that cannot be recoloured. `none` and
 * `currentColor` are fine: both defer to the wrapper, which is the point.
 * A few lucide icons legitimately use `fill="currentColor"` for solid dots.
 */
function shapesOf(name) {
  let source;

  try {
    source = readFileSync(join(iconsDir, `${name}.svg`), 'utf8');
  } catch {
    throw new Error(
      `No lucide icon named "${name}". Check the spelling against node_modules/lucide-static/icons/.`,
    );
  }

  const body = source.slice(source.indexOf('>', source.indexOf('<svg')) + 1, source.lastIndexOf('</svg>'));

  const shapes = body
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  if (shapes.length === 0) {
    throw new Error(`Icon "${name}" produced no shapes.`);
  }

  for (const shape of shapes) {
    if (/\b(?:fill|stroke)="(?!none"|currentColor")/.test(shape)) {
      throw new Error(
        `Icon "${name}" hard-codes a colour: ${shape}\n` +
          'These icons take their colour from the text around them; this one would not.',
      );
    }
  }

  return shapes.map((shape) => `          ${shape}`).join('\n');
}

function replaceRegion(source, begin, end, body) {
  const from = source.indexOf(begin);
  const to = source.indexOf(end);

  if (from === -1 || to === -1 || to < from) {
    throw new Error(`Markers not found in icon.ts:\n  ${begin}\n  ${end}`);
  }

  return source.slice(0, from + begin.length) + '\n' + body + '\n' + source.slice(to);
}

const names = ICONS.map((name) => `  | '${name}'`).join('\n');

const cases = ICONS.map(
  (name) => `        @case ('${name}') {\n${shapesOf(name)}\n        }`,
).join('\n');

/**
 * Every subcategory in the megamenu must have an icon.
 *
 * The source of truth is docs/TAXONOMY.md - the approved artefact that
 * TaxonomySeeder already validates its own output against. Checking against
 * the document rather than the database keeps this gate offline and
 * deterministic, and means a subcategory added to the taxonomy fails here
 * before it can ship as a menu item with a placeholder chevron.
 *
 * Departments are deliberately not covered: the department rail has no icons.
 * See category-icons.ts.
 */
function checkCategoryCoverage() {
  const taxonomy = readFileSync(join(here, '..', '..', '..', 'docs', 'TAXONOMY.md'), 'utf8');
  const map = readFileSync(join(here, '..', 'src', 'app', 'core', 'layout', 'category-icons.ts'), 'utf8');

  const tree = taxonomy.slice(taxonomy.indexOf('```'), taxonomy.indexOf('```', taxonomy.indexOf('```') + 3));

  // Four leading spaces is a subcategory; "/c/x/" at column 0 is a department.
  const subcategories = [...tree.matchAll(/^ {4}([a-z0-9-]+)\/(?:\s|$)/gm)].map(([, slug]) => slug);
  const departments = [...tree.matchAll(/^\/c\/([a-z0-9-]+)\/$/gm)].map(([, slug]) => slug);

  if (subcategories.length === 0 || departments.length === 0) {
    throw new Error('Parsed no categories out of docs/TAXONOMY.md - has its tree block changed shape?');
  }

  // Both maps are in one file, so the slugs are read from their own blocks:
  // everything before DEPARTMENT_ICONS covers subcategories, everything after
  // covers departments. Reading the whole file would let an entry in the wrong
  // map satisfy the gate.
  const split = map.indexOf('const DEPARTMENT_ICONS');
  const slugsIn = (source) => new Set([...source.matchAll(/^\s{2}'?([a-z0-9-]+)'?:/gm)].map(([, s]) => s));

  const missing = [
    ...subcategories.filter((slug) => !slugsIn(map.slice(0, split)).has(slug)).map((s) => `subcategory ${s}`),
    ...departments.filter((slug) => !slugsIn(map.slice(split)).has(slug)).map((s) => `department ${s}`),
  ];

  if (missing.length > 0) {
    console.error(
      `${missing.length} categor(y/ies) in docs/TAXONOMY.md have no icon:\n` +
        missing.map((entry) => `  ${entry}`).join('\n') +
        '\nAdd them to src/app/core/layout/category-icons.ts.',
    );
    process.exit(1);
  }

  return { subcategories: subcategories.length, departments: departments.length };
}

const current = readFileSync(target, 'utf8');
const next = replaceRegion(
  replaceRegion(current, NAMES_BEGIN, NAMES_END, names),
  CASES_BEGIN,
  CASES_END,
  cases,
);

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error(
      'icon.ts does not match what tools/icons.mjs generates.\n' +
        'Run `npm run icons` and commit the result.',
    );
    process.exit(1);
  }

  const coverage = checkCategoryCoverage();

  console.log(
    `Icons verified: ${ICONS.length} inlined from lucide-static, ` +
      `${coverage.departments} departments and ${coverage.subcategories} subcategories covered.`,
  );
  process.exit(0);
}

writeFileSync(target, next);
console.log(`Icons written: ${ICONS.length} inlined into src/app/shared/icon.ts.`);
